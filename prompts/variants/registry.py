"""The variant registry: id -> frozen prompt layer + provenance.

A VARIANT is the interviewer's whole TEXT-TURN prompt layer at one git commit:

  1. build_adaptive_interviewer_messages  (prompts/interview_prompts_v2.py)
  2. PACKET_RULES                          (services/interviewer_mode.py _PACKET_RULES)
  3. assess_context_with_llm + prompt      (services/interviewer_decision.py), the
     context assessor whose output feeds the response-function decision

v1 of the arena froze only (1); the other two silently came from the deployed tree
for BOTH arms, so "the branch" arm was part branch, part main. Frozen variants are
now generated by tools/arena_snapshot.py straight from git and verified against it
(python -m tools.arena_snapshot --check), and tests/test_arena_variants.py pins each
file's SHA256 so an accidental edit fails loudly instead of quietly invalidating
every vote recorded against it.

Adding a variant (e.g. the branch after more changes):
    python -m tools.arena_snapshot --ref <branch> --id <new-id> --label "<label>"
then add the row it prints below and pin the SHA it prints in the test.

What a variant can NOT carry: code. If a branch changes signals, decision logic,
scoring or voice, the tool says so and the arm runs main's version of that code.
"""
from __future__ import annotations

import ast
import hashlib
import inspect
import os
import textwrap
from typing import Any, Callable, Dict, List, Optional

from prompts.interview_prompts_v2 import (
    build_adaptive_interviewer_messages as _live_builder,
)
from prompts.variants import baseline_main_v12 as _baseline_main
from prompts.variants import patched_v12_2026_10_14 as _patched


def _sha256_of(module: Any) -> str:
    """Content hash of a variant module's source file, for drift detection."""
    path = getattr(module, "__file__", None)
    if not path or not os.path.exists(path):
        return ""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


