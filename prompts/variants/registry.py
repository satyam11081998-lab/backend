VARIANTS: Dict[str, Dict[str, Any]] = {s["id"]: s for s in _SPECS}

# What the arena opens with: main against the branch it is evaluating.
DEFAULT_ARM_A = "baseline-main"
DEFAULT_ARM_B = "patched-2026-10-14"


def variant_ids() -> List[str]:
    return [s["id"] for s in _SPECS]


def get_variant(variant_id: str) -> Dict[str, Any]:
    """Look up a variant. Raises KeyError for an unknown id -- the caller turns that
    into a 400 rather than silently falling back, because a silent fallback would
    attribute one variant's replies to another."""
    if variant_id not in VARIANTS:
        raise KeyError(variant_id)
    return VARIANTS[variant_id]


def get_builder(variant_id: str) -> Callable[..., List[Dict[str, str]]]:
    return get_variant(variant_id)["builder"]


def get_overrides(variant_id: str,
                  client_factory: Optional[Callable[[], Any]] = None) -> Optional[Dict[str, Any]]:
    """The rest of a frozen variant's prompt layer, in the shape the engine takes
    (stream_interviewer_reply(prompt_overrides=...)). None for `live`: the engine then
    uses the deployed packet rules and assessor, which ARE the live variant.

    client_factory is how the frozen assessor gets its OpenAI client (a snapshot
    imports nothing from the repo). The arena passes its own, so a test that fakes the
    arena's client fakes the assessor's too."""
    spec = get_variant(variant_id)
    mod = spec["module"]
    if mod is None:
        return None
    if client_factory is None:
        from services.ai_providers import openai_client as client_factory  # noqa: N813
    mod.openai_client = client_factory
    return {"packet_rules": mod.PACKET_RULES, "assessor": mod.assess_context_with_llm}


def describe_variants() -> List[Dict[str, Any]]:
    """Public, JSON-safe catalogue for the admin UI. No callables."""
    out = []
    for s in _SPECS:
        out.append({
            "id": s["id"],
            "label": s["label"],
            "description": s["description"],
            "origin": s["origin"],
            "frozen": bool(s["frozen"]),
            "sha256": _sha256_of(s["module"])[:12] if s["module"] is not None else None,
        })
    return out


def live_fingerprint() -> str:
    """Content hash of the LIVE prompt file in this deployment."""
    import prompts.interview_prompts_v2 as live_mod
    return _sha256_of(live_mod)


def _code_shape(fn: Any) -> Optional[str]:
    """A function's code with comments and formatting ignored."""
    try:
        return ast.dump(ast.parse(textwrap.dedent(inspect.getsource(fn))))
    except Exception:  # noqa: BLE001
        return None


def _stack(prompts_mod: Any, packet_rules: Any, assessor_prompt: Any, assessor_fn: Any) -> tuple:
    return (
        getattr(prompts_mod, "CASE_INTERVIEWER_V2", None),
        getattr(prompts_mod, "GUESSTIMATE_INTERVIEWER_V2", None),
        packet_rules,
        assessor_prompt,
        _code_shape(assessor_fn) if assessor_fn else None,
    )


def live_matches() -> Optional[str]:
    """Which frozen snapshot the deployed prompt layer EQUALS, if any -- all three
    pieces, compared as composed text (and the assessor as code), not file bytes,
    because a snapshot carries a banner its sources do not.

    Answers the question that otherwise silently wrecks a session: "am I comparing
    against what is actually serving users right now?" None when the deployed layer
    matches no snapshot (mid-edit, or a stack nobody has snapshotted)."""
    import prompts.interview_prompts_v2 as live_mod
    from services import interviewer_decision as live_dec
    from services import interviewer_mode as live_mode

    live = _stack(live_mod, getattr(live_mode, "_PACKET_RULES", None),
                  getattr(live_dec, "_ASSESSOR_PROMPT", None),
                  getattr(live_dec, "assess_context_with_llm", None))
    if not all(live):
        return None
    for spec in _SPECS:
        mod = spec["module"]
        if mod is None:
            continue
        snap = _stack(mod, getattr(mod, "PACKET_RULES", None),
                      getattr(mod, "_ASSESSOR_PROMPT", None),
                      getattr(mod, "assess_context_with_llm", None))
        if snap == live:
            return spec["id"]
    return None


def fingerprint(variant_id: str) -> Optional[str]:
    """Full content hash of a frozen variant, stored with every recorded vote so a
    later reader can tell whether the baseline was the same one they think it was."""
    spec = get_variant(variant_id)
    if spec["module"] is None:
        return None
    return _sha256_of(spec["module"])
