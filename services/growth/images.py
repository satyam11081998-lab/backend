def gemini_vision(prompt: str, images: List[bytes]) -> str:
    from google.genai import types
    client = _client()
    parts: List[Any] = []
    for i, b in enumerate(images):
        parts += [f"Photo {i + 1}:", types.Part.from_bytes(data=b, mime_type="image/jpeg")]
    parts.append(prompt)
    last: Optional[Exception] = None
    for model in vision_models():
        try:
            resp = client.models.generate_content(
                model=model, contents=parts,
                config=types.GenerateContentConfig(response_mime_type="application/json", temperature=0.0))
            return resp.text or ""
        except Exception as e:  # noqa: BLE001
            last = e
            if _is_gone(e):
                _dead[model] = time.time()
    raise RuntimeError(f"no Gemini vision model answered: {type(last).__name__ if last else 'none configured'}")


def _thumb_jpeg(data: bytes, width: int = 480) -> bytes:
    from PIL import Image
    with Image.open(io.BytesIO(data)) as im:
        im = im.convert("RGB")
        if im.width > width:
            im = im.resize((width, round(im.height * width / im.width)))
        b = io.BytesIO()
        im.save(b, format="JPEG", quality=80)
        return b.getvalue()


def judge(cands: List[Dict[str, Any]], want: str, title: str, *, vision: Callable = gemini_vision,
          fetch: Callable = _http_bytes) -> Optional[Dict[str, Any]]:
    """The candidate the vision model says shows the subject, or None (strict: none is a valid answer)."""
    shown, thumbs = [], []
    for c in cands:
        try:
            thumbs.append(_thumb_jpeg(fetch(c["thumb_url"], 4_000_000)))
            shown.append(c)
        except Exception:
            continue
        if len(shown) >= 8:
            break
    if not shown:
        return None
    raw = vision(_JUDGE.format(title=title, want=want, n=len(shown)), thumbs)
    m = re.search(r"\{.*\}", raw or "", re.S)
    try:
        best = json.loads(m.group(0)).get("best") if m else None
    except ValueError:
        best = None
    if isinstance(best, str) and best.strip().isdigit():
        best = int(best.strip())
    if isinstance(best, (int, float)) and 1 <= int(best) <= len(shown):
        return shown[int(best) - 1]
    return None


def photo_credit(c: Dict[str, Any]) -> str:
    who = c.get("creator") or "Unknown photographer"
    site = c.get("source") or "Wikimedia Commons"
    lic = c.get("license") or "open licence"
    # "Jane Doe / Pexels, Pexels licence" reads badly; the site name already carries the licence there.
    if site.lower() in lic.lower():
        return f"Photo: {who} / {site}"
    return f"Photo: {who} / {site}, {lic}"


