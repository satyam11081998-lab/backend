def picture_order() -> List[str]:
    """Which picture sources to use, in order. Default: real photographs only.

    Gemini image generation is a PAID-ONLY feature — Google's pricing page lists image output as "Not available"
    on the free tier for every current image model, and every call on this key has returned
    429 RESOURCE_EXHAUSTED since the feature shipped. Owner decision 2026-10-27: do not put the project on a paid
    image plan. So generation is off by default and nothing here can spend money.

    Everything still in the chain is free: Wikimedia Commons and Openverse need no key, and the Gemini vision
    model that judges the candidates is a flash text/vision model on the free tier (the same family the writer
    already runs on) — when its free rate limit bites, `heuristic_pick`/`fallback_pick` take over.

    Set DAILY_BLOG_PICTURES="photos,gemini" to turn generation back on, but only once the key is on a paid plan.
    """
    raw = (os.getenv("DAILY_BLOG_PICTURES") or "photos").lower()
    out = [x.strip() for x in raw.split(",") if x.strip() in ("photos", "gemini")]
    return out or ["photos"]


def available() -> bool:
    """Gemini (generation and the photo judge) is usable."""
    if not (os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")):
        return False
    try:
        import google.genai  # noqa: F401
        return True
    except Exception:
        return False


def _client():
    from google import genai
    return genai.Client(api_key=os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY"))


def _is_gone(e: Exception) -> bool:
    t = f"{type(e).__name__} {e}".lower()
    return any(k in t for k in ("404", "not_found", "not found", "no longer available", "is not supported"))


# ============================================================================ Gemini generation
# Google's image models are not all named "*image*": the Nano Banana line (gemini-nano-banana-2.1, currently the
# cheapest at ~$0.034 per 1K image) has no "image" in its id, so the old `"image" in name` test filtered it out and
# the key's best image model was never tried. Match the family names too.
_IMAGE_NAME = re.compile(r"image|banana|imagen", re.I)


def image_models() -> List[str]:
    """Gemini image models to try: DAILY_BLOG_IMAGE_MODEL, then what this key lists (newest first)."""
    out: List[str] = []
    env = (os.getenv("DAILY_BLOG_IMAGE_MODEL") or "").strip()
    if env:
        out.append(env.removeprefix("models/"))
    if time.time() - _models["at"] > 3600:
        names: List[str] = []
        try:
            for m in _client().models.list():
                name = (getattr(m, "name", "") or "").removeprefix("models/")
                actions = getattr(m, "supported_actions", None) or []
                if name.startswith("gemini") and _IMAGE_NAME.search(name) and (not actions or "generateContent" in actions):
                    names.append(name)
        except Exception as e:  # noqa: BLE001
            print(f"[insights images] model list failed: {type(e).__name__}: {e}")

        def key(n: str):
            m = re.search(r"gemini-(\d+(?:\.\d+)?)", n)
            return (-(float(m.group(1)) if m else 0.0), "preview" in n, "pro" in n)
        _models.update(at=time.time(), list=sorted(dict.fromkeys(names), key=key))
    for n in _models["list"] + ["gemini-2.5-flash-image"]:
        if n not in out:
            out.append(n)
    return [m for m in out if time.time() - _dead.get(m, 0) > 6 * 3600]


def gemini_image(prompt: str, aspect: str = "16:9") -> Dict[str, Any]:
    """{bytes, mime, model} from the first Gemini image model that answers. Raises with every model's error."""
    from google.genai import types
    client = _client()
    errors = []
    for model in image_models():
        attempts = [
            dict(response_modalities=["IMAGE"], image_config=types.ImageConfig(aspect_ratio=aspect)),
            dict(response_modalities=["TEXT", "IMAGE"], image_config=types.ImageConfig(aspect_ratio=aspect)),
            dict(response_modalities=["TEXT", "IMAGE"]),
        ]
        for i, kw in enumerate(attempts):
            try:
                resp = client.models.generate_content(model=model, contents=prompt,
                                                      config=types.GenerateContentConfig(**kw))
                for cand in getattr(resp, "candidates", None) or []:
                    for part in getattr(getattr(cand, "content", None), "parts", None) or []:
                        blob = getattr(part, "inline_data", None)
                        if blob is not None and getattr(blob, "data", None):
                            return {"bytes": blob.data, "mime": getattr(blob, "mime_type", "image/png"), "model": model}
                reason = ""
                fb = getattr(resp, "prompt_feedback", None)
                if fb is not None and getattr(fb, "block_reason", None):
                    reason = f" (blocked: {fb.block_reason})"
                errors.append(f"{model}: no image in the answer{reason}")
                break
            except Exception as e:  # noqa: BLE001
                if _is_gone(e):
                    _dead[model] = time.time()
                    errors.append(f"{model}: not available on this key")
                    break
                if i == len(attempts) - 1:
                    errors.append(f"{model}: {type(e).__name__}: {str(e)[:140]}")
    raise RuntimeError("; ".join(errors)[:600] or "no Gemini image model available")


# ============================================================================ open-licensed photos
# 7s, not 12s. api.openverse.org read-times-out from Render often enough that it is the dominant cost of a
# backfill: six queries x two sources x 12s is 144 seconds of pure waiting per picture slot, three slots per
# article, three articles per click. Commons answers in well under a second when it answers at all, so a shorter
# timeout costs nothing real and the circuit breaker below stops a dead source being retried at all.
_HTTP_TIMEOUT = 7

# A source that times out or refuses a connection is skipped for 10 minutes rather than retried for every query.
_source_dead: Dict[str, float] = {}
_SOURCE_COOLDOWN = 600
# Whole-article ceiling on photo search, so one slow source can never hold a backfill open for minutes.
PHOTO_BUDGET_S = 45
# The person/event terms matter because `heuristic_pick` runs without the vision judge whenever Gemini is out of
# quota, and the judge's "no close-up portraits of an identifiable person" rule would otherwise go unenforced.
# Wikimedia Commons is full of PIB portraits of governors and ministers, and a story about an RBI rate rise would
# happily take "Sanjay Malhotra, Governor of the Reserve Bank of India" as its hero and its link preview.
_BAD_TITLE = re.compile(r"\b(logo|logos|map|maps|flag|coat of arms|emblem|diagram|chart|graph|icon|seal|signature|"
                        r"screenshot|infographic|poster|banner|svg|plan|blueprint|stamp|currency note|document|"
                        r"letter|newspaper|cartoon|illustration|drawing|painting|"
                        r"portrait|headshot|mugshot|selfie|"
                        r"governor|minister|ministry|chairman|chairperson|ceo|cfo|president|secretary|"
                        r"commissioner|ambassador|delegation|"
                        r"press conference|press meet|speaking|speech|addressing|interview|"
                        r"award|awards|ceremony|felicitation|inauguration|summit|conclave|visit|meeting with|"
                        r"protest|rally|strike|funeral|accident|disaster|"
                        # War and conflict: the topic picker already refuses these as story subjects, and the
                        # picture search must not smuggle one back in. Live example that made this necessary:
                        # a Starlink article's second Wikipedia hit was "Starlink in the Russo-Ukrainian war",
                        # whose lead image is two politicians holding a user terminal.
                        r"war|wartime|conflict|invasion|military|troops?|soldiers?|ukrain\w*|russo[- ]\w+)\b", re.I)


def _http_json(url: str, params: Dict[str, Any]) -> Dict[str, Any]:
    import requests
    r = requests.get(url, params=params, timeout=_HTTP_TIMEOUT, headers={"User-Agent": UA, "Accept": "application/json"})
    r.raise_for_status()
    return r.json()


def _http_bytes(url: str, limit: int = 15_000_000) -> bytes:
    import requests
    with requests.get(url, timeout=20, headers={"User-Agent": UA}, stream=True) as r:
        r.raise_for_status()
        buf = io.BytesIO()
        for chunk in r.iter_content(65536):
            buf.write(chunk)
            if buf.tell() > limit:
                raise ValueError("image too large")
        return buf.getvalue()


def license_ok(name: str) -> bool:
    """Licences that allow commercial use and resizing: CC0, public domain, CC BY, CC BY-SA. Not NC, not ND."""
    t = (name or "").lower().replace("_", " ").replace("-", " ")
    if not t or any(x in t for x in (" nc", "noncommercial", "non commercial", " nd", "noderiv", "no deriv", "fair use",
                                     "all rights", "copyrighted")):
        return False
    return any(x in t for x in ("cc0", "public domain", "pdm", "cc by", "attribution"))


def _strip_html(s: str) -> str:
    return re.sub(r"\s+", " ", _html.unescape(re.sub(r"(?s)<[^>]+>", " ", s or ""))).strip()


def search_commons(query: str, *, http: Callable = _http_json, limit: int = 12) -> List[Dict[str, Any]]:
    data = http("https://commons.wikimedia.org/w/api.php", {
        "action": "query", "format": "json", "generator": "search", "gsrsearch": f"filetype:bitmap {query}",
        "gsrnamespace": 6, "gsrlimit": limit, "prop": "imageinfo", "iiprop": "url|size|mime|extmetadata",
        "iiurlwidth": 1920,  # one of Wikimedia's standard thumbnail widths
    })
    pages = ((data or {}).get("query") or {}).get("pages") or {}
    pages = list(pages.values()) if isinstance(pages, dict) else list(pages)
    pages.sort(key=lambda p: p.get("index", 0))
    out = []
    for p in pages:
        ii = (p.get("imageinfo") or [{}])[0]
        meta = ii.get("extmetadata") or {}
        lic = _strip_html((meta.get("LicenseShortName") or {}).get("value") or "")
        title = re.sub(r"^File:", "", p.get("title") or "").rsplit(".", 1)[0]
        if ii.get("mime") not in ("image/jpeg", "image/png", "image/webp") or not license_ok(lic):
            continue
        if _BAD_TITLE.search(title) or (ii.get("width") or 0) < 900:
            continue
        big = ii.get("thumburl") or ii.get("url") or ""
        thumb = _commons_thumb(ii.get("url") or big, 500)
        out.append({
            "source": "Wikimedia Commons", "title": title, "page_url": ii.get("descriptionurl") or "",
            "image_url": big, "thumb_url": thumb, "width": ii.get("width"), "height": ii.get("height"),
            "license": lic, "license_url": _strip_html((meta.get("LicenseUrl") or {}).get("value") or ""),
            "creator": _strip_html((meta.get("Artist") or {}).get("value") or "")[:120],
        })
    return out


def _commons_thumb(original: str, width: int) -> str:
    """upload.wikimedia.org/wikipedia/commons/a/ab/X.jpg -> .../commons/thumb/a/ab/X.jpg/500px-X.jpg"""
    m = re.match(r"(https://upload\.wikimedia\.org/wikipedia/commons)/(?!thumb/)([0-9a-f]/[0-9a-f]{2})/([^/?#]+)$", original or "")
    if not m:
        return original
    return f"{m.group(1)}/thumb/{m.group(2)}/{m.group(3)}/{width}px-{m.group(3)}"


_OV_LICENSE = {"cc0": "CC0", "pdm": "Public domain", "by": "CC BY", "by-sa": "CC BY-SA"}


def search_openverse(query: str, *, http: Callable = _http_json, limit: int = 20) -> List[Dict[str, Any]]:
    data = http("https://api.openverse.org/v1/images/", {
        "q": query, "license_type": "commercial,modification", "category": "photograph", "mature": "false",
        "page_size": limit,
    })
    out = []
    for r in (data or {}).get("results") or []:
        code = (r.get("license") or "").lower()
        if code not in _OV_LICENSE or r.get("mature"):
            continue
        lic = _OV_LICENSE[code] + (f" {r.get('license_version')}" if r.get("license_version") and code not in ("pdm",) else "")
        title = r.get("title") or ""
        if _BAD_TITLE.search(title) or (r.get("width") and r["width"] < 900):
            continue
        provider = (r.get("source") or r.get("provider") or "").replace("_", " ")
        out.append({
            "source": {"wikimedia": "Wikimedia Commons", "flickr": "Flickr"}.get(provider, provider.title() or "Openverse"),
            "title": title, "page_url": r.get("foreign_landing_url") or "", "image_url": r.get("url") or "",
            "thumb_url": r.get("thumbnail") or r.get("url") or "", "width": r.get("width"), "height": r.get("height"),
            "license": lic, "license_url": r.get("license_url") or "", "creator": (r.get("creator") or "")[:120],
        })
    return out


def _timed_out(e: Exception) -> bool:
    return any(k in type(e).__name__.lower() for k in ("timeout", "connection"))


def search_wikipedia(query: str, *, http: Callable = _http_json, limit: int = 3) -> List[Dict[str, Any]]:
    """The lead image of the Wikipedia article that matches this subject. No key, no signup.

    This is the right tool for exactly the queries that were failing. The writer plans proper-noun subjects —
    "Tata Sons building Mumbai", "Reserve Bank of India Mumbai headquarters", "Jawaharlal Nehru Port" — and a
    full-text search of Commons is bad at finding the one good photograph of a named thing among thousands of
    loosely tagged files. Wikipedia has already done that curation: a notable company, building, port or city has
    a lead image chosen by editors, and it is hosted on Commons with a real licence.

    Two calls: Wikipedia search + page image, then Commons imageinfo for the licence (reusing the same
    extmetadata parsing and the same licence filter as search_commons, so nothing unlicensed can slip in).

    Note the logo hazard: a company's Wikipedia page image is often its wordmark. `_BAD_TITLE` rejects anything
    with "logo"/"emblem" in the file name, and the mime filter drops SVG, which is what most wordmarks are.
    """
    data = http("https://en.wikipedia.org/w/api.php", {
        "action": "query", "format": "json", "generator": "search", "gsrsearch": query,
        "gsrnamespace": 0, "gsrlimit": limit, "prop": "pageimages", "piprop": "original|name",
    })
    pages = ((data or {}).get("query") or {}).get("pages") or {}
    pages = list(pages.values()) if isinstance(pages, dict) else list(pages)
    pages.sort(key=lambda p: p.get("index", 0))
    files = [(p.get("pageimage"), p.get("title")) for p in pages if p.get("pageimage")]
    if not files:
        return []

    # ONLY Wikipedia's own top-ranked article. Taking the second and third results is how a live run answered
    # "Bombay Stock Exchange" with a photograph of the New York Stock Exchange and "Jawaharlal Nehru Port" with
    # a suburban train: those pages are related to the query but are not the subject.
    fname, article = files[0]

    # ...and the top article still has to be about what was asked for. Half the query's meaningful words is the
    # right bar, not more: the writer's queries are wordier than article titles ("Tata Sons Bombay House" vs the
    # article "Bombay House"), so a stricter threshold threw away correct matches.
    q_t = _tokens(query)
    if not q_t or len(q_t & _tokens(article or "")) / len(q_t) < 0.5:
        return []

    # imageinfo from en.wikipedia, not commons.wikimedia: enwiki serves metadata for Commons-hosted files AND
    # for files hosted locally, so asking Commons directly silently missed the local ones.
    info = http("https://en.wikipedia.org/w/api.php", {
        "action": "query", "format": "json", "titles": f"File:{fname}",
        "prop": "imageinfo", "iiprop": "url|size|mime|extmetadata", "iiurlwidth": 1920,
    })
    pages2 = ((info or {}).get("query") or {}).get("pages") or {}
    pages2 = list(pages2.values()) if isinstance(pages2, dict) else list(pages2)
    if not pages2:
        return []
    ii = (pages2[0].get("imageinfo") or [{}])[0]
    meta = ii.get("extmetadata") or {}
    lic = _strip_html((meta.get("LicenseShortName") or {}).get("value") or "")
    title = re.sub(r"^File:", "", fname).replace("_", " ").rsplit(".", 1)[0]

    if ii.get("mime") not in ("image/jpeg", "image/png", "image/webp") or not license_ok(lic):
        return []
    if _BAD_TITLE.search(title) or _BAD_TITLE.search(article or ""):
        return []
    # 640, not the 900 the generic searches use. Relevance is already guaranteed here — this is the lead image
    # of the article about the exact subject — so the trade-off flips: a slightly soft but correct photograph of
    # Bombay House (808 px) or Jawaharlal Nehru Port (700 px) beats no photograph, and both were being discarded.
    if (ii.get("width") or 0) < 640:
        return []

    big = ii.get("thumburl") or ii.get("url") or ""
    return [{
        # The article name is a far better relevance signal than the file name: heuristic_pick scores the title,
        # and "Bombay House" tells it more than "Bombay house mast.jpg" does.
        "source": "Wikimedia Commons", "title": f"{article} — {title}"[:160],
        "page_url": ii.get("descriptionurl") or "", "image_url": big,
        "thumb_url": _commons_thumb(ii.get("url") or big, 500),
        "width": ii.get("width"), "height": ii.get("height"), "license": lic,
        "license_url": _strip_html((meta.get("LicenseUrl") or {}).get("value") or ""),
        "creator": _strip_html((meta.get("Artist") or {}).get("value") or "")[:120],
    }]


def search_pixabay(query: str, *, limit: int = 20) -> List[Dict[str, Any]]:
    """Pixabay — the same role as Pexels, a different free key. Set PIXABAY_API_KEY; no key means a clean no-op.

    Added because Pexels paused new API-key issuance on 2026-10-27. Whichever of the two you can actually get a
    key for, the chain works; with neither, Commons and Wikipedia carry it.
    """
    key = (os.getenv("PIXABAY_API_KEY") or "").strip()
    if not key:
        return []
    data = _http_json("https://pixabay.com/api/", {
        "key": key, "q": query, "image_type": "photo", "orientation": "horizontal",
        "per_page": max(3, limit), "safesearch": "true",
    })
    out = []
    for h in (data or {}).get("hits") or []:
        title = (h.get("tags") or "").strip()
        if not title or _BAD_TITLE.search(title) or (h.get("imageWidth") or 0) < 900:
            continue
        out.append({
            "source": "Pixabay", "title": title, "page_url": h.get("pageURL") or "",
            "image_url": h.get("largeImageURL") or "", "thumb_url": h.get("webformatURL") or "",
            "width": h.get("imageWidth"), "height": h.get("imageHeight"),
            "license": "Pixabay licence", "license_url": "https://pixabay.com/service/license-summary/",
            "creator": (h.get("user") or "")[:120],
        })
    return [c for c in out if c["image_url"] and c["thumb_url"]]


def search_pexels(query: str, *, limit: int = 15) -> List[Dict[str, Any]]:
    """Pexels — free API key, no payment, and far deeper coverage of business subjects than Commons.

    Commons and Openverse are thin on exactly what this publication needs: the admin log is full of
    "no open-licensed photo found for: delivery executive scooter india" and "8 photo(s) found for
    'Navi Mumbai data centre', none showed the subject closely enough". Pexels has thousands of usable
    editorial-style business photographs and its licence allows commercial use and modification.

    Entirely optional: with no PEXELS_API_KEY this returns [] and the chain is exactly as it was.
    Attribution is not required by the Pexels licence, but the photographer is credited anyway — the page
    already has the furniture for it and crediting a photographer costs nothing.
    """
    key = (os.getenv("PEXELS_API_KEY") or "").strip()
    if not key:
        return []
    import requests
    r = requests.get("https://api.pexels.com/v1/search",
                     params={"query": query, "per_page": limit, "orientation": "landscape"},
                     headers={"Authorization": key, "User-Agent": UA}, timeout=_HTTP_TIMEOUT)
    r.raise_for_status()
    out = []
    for p in (r.json() or {}).get("photos") or []:
        title = (p.get("alt") or "").strip()
        if not title or _BAD_TITLE.search(title) or (p.get("width") or 0) < 900:
            continue
        src = p.get("src") or {}
        out.append({
            "source": "Pexels", "title": title, "page_url": p.get("url") or "",
            "image_url": src.get("large2x") or src.get("original") or "",
            "thumb_url": src.get("medium") or src.get("small") or "",
            "width": p.get("width"), "height": p.get("height"),
            "license": "Pexels licence", "license_url": "https://www.pexels.com/license/",
            "creator": (p.get("photographer") or "")[:120],
        })
    return [c for c in out if c["image_url"] and c["thumb_url"]]


def candidates(queries: List[str], *, searchers: Optional[List[Callable]] = None, used: Optional[set] = None,
               errors: Optional[List[str]] = None, cap: int = 10, deadline: Optional[float] = None
               ) -> List[Dict[str, Any]]:
    """Photos for the queries from every source, deduplicated, landscape and large first.

    Two guards keep a slow source from eating the whole run: a source that times out is skipped for ten minutes
    (`_source_dead`), and the caller's `deadline` stops the sweep outright. Whatever has been found by then is
    returned — a shorter candidate list still produces a picture, where waiting produces nothing.
    """
    # Order is precision first, then reliability:
    #   wikipedia  the curated lead image of the named subject — the most likely to be the right photo, keyless
    #   commons    full-text search of the same corpus, for everything Wikipedia has no article for
    #   pexels     rich editorial stock; no-op without a key (issuance was paused 2026-10-27)
    #   pixabay    the same role, a different free key; no-op without one
    #   openverse  last: it is the source that read-times-out from Render, and the circuit breaker usually
    #              skips it before it costs anything
    searchers = searchers if searchers is not None else [
        search_wikipedia, search_commons, search_pexels, search_pixabay, search_openverse,
    ]
    used = used or set()
    seen, out = set(), []
    for q in [q for q in queries if q and q.strip()][:3]:
        if deadline and time.time() > deadline:
            if errors is not None:
                errors.append("photo search hit its time budget")
            break
        for s in searchers:
            name = getattr(s, "__name__", "search")
            if time.time() - _source_dead.get(name, 0) < _SOURCE_COOLDOWN:
                continue
            try:
                for c in s(q.strip()):
                    key = c["image_url"]
                    if key and key not in seen and key not in used:
                        seen.add(key)
                        out.append(c)
            except Exception as e:  # noqa: BLE001
                if _timed_out(e):
                    _source_dead[name] = time.time()
                if errors is not None:
                    errors.append(f"{name}('{q[:40]}'): {type(e).__name__}"
                                  + (" - skipping this source for 10 min" if _timed_out(e) else ""))

    def rank(c):
        w, h = c.get("width") or 0, c.get("height") or 1
        ratio = w / h if h else 0
        return (0 if 1.25 <= ratio <= 2.2 else 1, -min(w, 4000))
    out.sort(key=rank)
    return out[:cap]


_JUDGE = """You are the photo editor of MECE Insights, a long-form business magazine for Indian MBA students.
Article: "{title}"
Ideally this picture shows: {want}

Below are {n} candidate photographs, numbered 1 to {n} in order. Pick the ONE that best illustrates the story for a \
reader, in this order of preference:
  1. it shows the exact subject named above (that company's building, that port, that product, that activity);
  2. failing that, it is an honest editorial photograph of the same setting or sector (a bank branch for a banking \
story, a container terminal for a trade story, a street market for a consumption story) that a magazine would run \
beside this article. The caption printed under it says what it actually shows, so a representative photograph is \
acceptable and is far better than no photograph at all.

Always reject, whatever else is on offer: logos, wordmarks, maps, flags, charts, diagrams, screenshots, documents, \
posters, images dominated by text or watermarks, close-up portraits of an identifiable person, and anything sad, \
violent, political or otherwise sensitive. Also reject anything blurry or too small to print large.
Answer null ONLY when every candidate falls in one of those reject categories or is plainly about a different topic.
Return ONLY JSON: {{"best": <number or null>, "why": "<one short sentence>"}}"""

# Words that carry no signal when scoring a photo's title against what a slot wants.
_STOP = {
    "the", "a", "an", "of", "and", "or", "in", "on", "at", "to", "for", "with", "from", "by", "its", "their",
    "india", "indian", "new", "view", "photo", "image", "file", "wikimedia", "commons", "jpg", "png", "jpeg",
}


def _tokens(s: str) -> set:
    return {w for w in re.findall(r"[a-z]{3,}", (s or "").lower()) if w not in _STOP}


def _landscape(c: Dict[str, Any], lo: float = 1.2, hi: float = 2.6) -> bool:
    """Shape is the cheapest portrait filter there is: a close-up of a person is almost always taller than wide."""
    w, h = c.get("width") or 0, c.get("height") or 0
    return bool(w and h and lo <= w / h <= hi)


def heuristic_pick(cands: List[Dict[str, Any]], want: str) -> Optional[Dict[str, Any]]:
    """A photo chosen without a model: the candidate whose title overlaps THIS SLOT'S SUBJECT.

    The safety net for the two ways the Gemini judge stops working — it runs out of quota (429 RESOURCE_EXHAUSTED)
    or every model on the key errors. Before this, a judge failure threw away a perfectly good candidate set and the
    article shipped with no picture at all.

    Scored against the subject ONLY, never against the search queries. Scoring against the queries would be
    circular — the candidates were retrieved *by* those queries, so everything would "match" and a crude-oil
    pipeline story could take a solar farm because the generic energy query happened to carry more tokens.
    Only landscape candidates are eligible, which also keeps portraits out on this judge-free path.
    """
    want_t = _tokens(want)
    if not want_t:
        return None
    best, best_score = None, 0.0
    for c in cands:
        if not _landscape(c):
            continue
        overlap = _tokens(c.get("title") or "") & want_t
        if not overlap:
            continue
        score = len(overlap) * 2.0 + min((c.get("width") or 0) / 4000.0, 1.0)
        if score > best_score:
            best, best_score = c, score
    return best


def fallback_pick(cands: List[Dict[str, Any]], slug: str) -> Optional[Dict[str, Any]]:
    """Pick from candidates found by the broad sector queries, where title overlap means nothing.

    `widen_queries` is a pure function of sector keywords, so every banking article generates the same query list
    and `candidates()` ranks them identically. Taking the top one would put the same photograph on every banking
    story on the site. The slug picks the offset instead: deterministic (the same post always gets the same photo,
    so a re-run is idempotent) but spread across the set, so four banking stories get four different photographs.
    Candidates arrive in query order, so this still prefers the first, most on-topic sector query.
    """
    pool = [c for c in cands if _landscape(c)] or [c for c in cands if (c.get("width") or 0) >= 900]
    if not pool:
        return None
    window = min(len(pool), 6)
    idx = int(hashlib.sha1((slug or "").encode("utf-8")).hexdigest(), 16) % window
    return pool[idx]


def recent_photo_urls(supabase, limit: int = 60) -> set:
    """Photos already used on other posts, so the same picture does not appear across the archive.

    `used` is per-article, which stopped one article repeating a photo but did nothing across articles — and the
    live site already shows the same IDBI branch photo turning up repeatedly. Best effort: any failure returns an
    empty set and the pipeline carries on.
    """
    out: set = set()
    try:
        rows = (supabase.table("seo_pages").select("content")
                .order("published_at", desc=True).limit(limit).execute().data or [])
    except Exception:  # noqa: BLE001
        return out
    for r in rows:
        c = r.get("content") or {}
        for img in ([c.get("hero")] if c.get("hero") else []) + (c.get("images") or []):
            src = (img or {}).get("source_url") or (img or {}).get("credit_url")
            if src:
                out.add(src)
    return out


