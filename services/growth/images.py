def widen_queries(item: Dict[str, Any], title: str) -> List[str]:
    """Broad sector scenes to fall back on when the writer's precise queries find nothing."""
    hay = " ".join(str(x) for x in (
        item.get("subject") or "", item.get("alt") or "", item.get("prompt") or "", title or "",
        " ".join(item.get("search") or []),
    )).lower()
    out: List[str] = []
    for words, queries in _SECTOR_QUERIES:
        # Whole words only. Bare substrings matched inside unrelated words -- "car" in "healthcare" and "scarce",
        # "power" in "empowerment", "trade" in "tradeoff", "gas" in "Vegas" -- and sent a healthcare story to a
        # car assembly line.
        if any(re.search(rf"\b{re.escape(w)}\b", hay) for w in words):
            out += queries
    return (out or _DEFAULT_QUERIES)[:3]


def find_photo(item: Dict[str, Any], title: str, used: set, *, search: Callable = candidates,
               pick: Callable = judge, fetch: Callable = _http_bytes, errors: Optional[List[str]] = None,
               slug: str = "", deadline: Optional[float] = None) -> Optional[Dict[str, Any]]:
    """{bytes, meta} for a real, openly licensed photo for this slot, or None.

    Two paths, deliberately scored differently (2026-10-27):

      PRECISE  the writer's own proper-noun queries. Candidates here are supposed to show the named subject, so a
               judge failure falls back to `heuristic_pick`, which demands a real title/subject overlap.
      WIDENED  broad sector scenes, tried only when the precise queries find nothing. Title overlap is meaningless
               here (the candidates were retrieved by those very queries), so `fallback_pick` chooses by slug
               instead: topical by construction, varied across articles, stable for one article.

    Either way the photo is landscape and has passed `_BAD_TITLE`, so the judge's hard rejects -- logos, maps,
    charts, portraits of identifiable people -- still hold on the judge-free path.
    """
    queries = [q for q in (item.get("search") or []) if isinstance(q, str) and q.strip()]
    if not queries and item.get("subject"):
        queries = [str(item["subject"])]
    precise = bool(queries)
    if not queries:
        queries = widen_queries(item, title)

    cands = search(queries, used=used, errors=errors, deadline=deadline)
    widened: List[str] = []
    if not cands and precise:
        widened = [q for q in widen_queries(item, title) if q not in queries]
        if widened:
            cands = search(widened, used=used, errors=errors, deadline=deadline)
    if not cands:
        if errors is not None:
            errors.append(f"no open-licensed photo found for: {', '.join(queries + widened)[:160]}")
        return None

    on_widened = bool(widened) or not precise
    want = str(item.get("subject") or item.get("alt") or item.get("prompt") or queries[0])[:300]

    def without_judge() -> Optional[Dict[str, Any]]:
        return fallback_pick(cands, f"{slug}/{item.get('after_section', 0)}") if on_widened \
            else heuristic_pick(cands, want)

    best = None
    try:
        best = pick(cands, want, title)
        if not best:
            best = without_judge()
            if best and errors is not None:
                errors.append(f"judge found none close enough for '{queries[0][:50]}'; used a sector photo"
                              if on_widened else
                              f"judge found none close enough for '{queries[0][:50]}'; used the closest match by title")
    except Exception as e:  # noqa: BLE001
        best = without_judge()
        if errors is not None:
            errors.append(f"photo judge unavailable ({type(e).__name__}); "
                          + ("used a sector photo" if (best and on_widened) else
                             "picked the closest match by title" if best else "no usable candidate"))
    if not best:
        if errors is not None:
            errors.append(f"{len(cands)} photo(s) found for '{queries[0][:60]}', none usable")
        return None
    data = fetch(best["image_url"])
    used.add(best["image_url"])
    return {"bytes": data, "meta": best}


# ============================================================================ storage
def to_web(data: bytes, width: int) -> Dict[str, Any]:
    """WebP for the page (resized to `width`) and a 1200 px JPEG for link previews, plus the page size."""
    from PIL import Image, ImageOps
    with Image.open(io.BytesIO(data)) as im:
        im = ImageOps.exif_transpose(im).convert("RGB")
        if im.width > width:
            im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
        w, h = im.size
        webp = io.BytesIO()
        try:
            im.save(webp, format="WEBP", quality=82, method=4)
            webp_bytes, webp_type = webp.getvalue(), "image/webp"
        except Exception:
            webp = io.BytesIO()
            im.save(webp, format="JPEG", quality=85, optimize=True, progressive=True)
            webp_bytes, webp_type = webp.getvalue(), "image/jpeg"
        # link previews (WhatsApp, LinkedIn, X) want a modest JPEG: 1200 px wide keeps it well under 300 KB
        og = im.resize((OG_WIDTH, round(h * OG_WIDTH / w)), Image.LANCZOS) if w > OG_WIDTH else im
        jpg = io.BytesIO()
        og.save(jpg, format="JPEG", quality=82, optimize=True, progressive=True)
        return {"web": webp_bytes, "web_type": webp_type, "jpeg": jpg.getvalue(), "width": w, "height": h}


_bucket_ready = {"ok": False}


def _ensure_bucket(supabase) -> None:
    if _bucket_ready["ok"]:
        return
    try:
        buckets = supabase.storage.list_buckets() or []
        names = [getattr(b, "name", None) or (b.get("name") if isinstance(b, dict) else None) for b in buckets]
        if BUCKET not in names:
            supabase.storage.create_bucket(BUCKET, options={"public": True})
        _bucket_ready["ok"] = True
    except Exception as e:  # noqa: BLE001 - the upload will say if it really is missing
        print(f"[insights images] bucket check: {type(e).__name__}: {e}")


def store(supabase, path: str, data: bytes, content_type: str) -> str:
    _ensure_bucket(supabase)
    st = supabase.storage.from_(BUCKET)
    st.upload(path, data, file_options={"content-type": content_type, "upsert": "true",
                                        "cache-control": "31536000"})
    url = st.get_public_url(path)
    return (url if isinstance(url, str) else (url or {}).get("publicUrl", "")).rstrip("?")


# ============================================================================ one article
def _save(supabase, slug: str, item: Dict[str, Any], role: str, n: int, data: bytes, *, upload: Callable,
          extra: Dict[str, Any]) -> Dict[str, Any]:
    web = to_web(data, HERO_WIDTH if role == "hero" else INLINE_WIDTH)
    tag = hashlib.sha1(data[:200_000]).hexdigest()[:8]
    ext = "webp" if web["web_type"] == "image/webp" else "jpg"
    url = upload(supabase, f"{slug}/{role}-{n}-{tag}.{ext}", web["web"], web["web_type"])
    res = {"url": url, "width": web["width"], "height": web["height"], "alt": (item.get("alt") or "")[:300],
           "caption": (item.get("caption") or "")[:300], **extra}
    if role == "hero":
        res["og_url"] = upload(supabase, f"{slug}/og-{tag}.jpg", web["jpeg"], "image/jpeg")
    else:
        res["after_section"] = int(item.get("after_section") or 1)
    return res


def make_images(supabase, slug: str, art: Dict[str, Any], *, title: str = "", generate: Callable = gemini_image,
                upload: Callable = store, photo: Callable = find_photo, order: Optional[List[str]] = None
                ) -> Dict[str, Any]:
    """{hero?, images: [...], errors: [...]} for an article's art direction. Never raises."""
    out: Dict[str, Any] = {"images": [], "errors": []}
    if not art:
        out["errors"].append("no art direction")
        return out
    order = order or picture_order()
    jobs = []
    if art.get("hero"):
        jobs.append(("hero", 0, art["hero"]))
    for i, item in enumerate((art.get("inline") or [])[:2]):
        jobs.append(("inline", i + 1, item))
    results: Dict[int, Dict[str, Any]] = {}

    # 1. real photos, one slot at a time so two slots never get the same photo. `used` is also seeded with the
    #    photos other posts already use, so a picture does not repeat across the archive.
    if "photos" in order:
        used: set = recent_photo_urls(supabase)
        deadline = time.time() + PHOTO_BUDGET_S
        for idx, (role, n, item) in enumerate(jobs):
            try:
                got = photo(item, title, used, errors=out["errors"], slug=slug, deadline=deadline)
                if got:
                    m = got["meta"]
                    results[idx] = _save(supabase, slug, item, role, n, got["bytes"], upload=upload, extra={
                        "credit": photo_credit(m), "credit_url": m.get("page_url") or "", "license": m.get("license"),
                        "license_url": m.get("license_url") or "", "source": "photo", "photo_title": m.get("title"),
                        "creator": m.get("creator") or "", "site": m.get("source") or "",
                        # the original file URL, so recent_photo_urls() can keep later posts off this photo
                        "source_url": m.get("image_url") or ""})
            except Exception as e:  # noqa: BLE001
                out["errors"].append(f"{role} photo: {type(e).__name__}: {str(e)[:120]}")

    # 2. Gemini for the slots still empty (in parallel)
    gen_jobs = [(idx, j) for idx, j in enumerate(jobs) if idx not in results and (j[2].get("prompt") or "").strip()]
    if "gemini" in order and gen_jobs:
        if generate is gemini_image and not available():
            out["errors"].append("Gemini image generation not available (GEMINI_API_KEY)")
        else:
            lock = threading.Lock()

            def run(job):
                idx, (role, n, item) = job
                try:
                    g = generate(f"{item['prompt'].strip()}\n\n{HOUSE_STYLE}", "16:9" if role == "hero" else "3:2")
                    res = _save(supabase, slug, item, role, n, g["bytes"], upload=upload,
                                extra={"credit": CREDIT, "source": "gemini", "model": g.get("model")})
                    with lock:
                        results[idx] = res
                except Exception as e:  # noqa: BLE001
                    with lock:
                        out["errors"].append(f"{role} (Gemini): {type(e).__name__}: {str(e)[:200]}")

            with ThreadPoolExecutor(max_workers=3) as ex:
                list(ex.map(run, gen_jobs))

    for idx, (role, _n, _item) in enumerate(jobs):
        if idx in results:
            if role == "hero":
                out["hero"] = results[idx]
            else:
                out["images"].append(results[idx])
    out["images"].sort(key=lambda x: x.get("after_section", 1))
    return out


